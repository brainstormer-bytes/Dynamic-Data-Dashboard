
-- V1: Initial database schema
-- Project: Dynamic Data Dashboard Builder

-- 1. USERS
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. WORKSPACES
CREATE TABLE workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by_user_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_workspaces_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 3. WORKSPACE MEMBERS
CREATE TABLE workspace_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(50) NOT NULL,
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_workspace_members_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces(id),

    CONSTRAINT fk_workspace_members_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_workspace_member
        UNIQUE (workspace_id, user_id)
);

-- 4. DATASETS
CREATE TABLE datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_datasets_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces(id),

    CONSTRAINT uq_datasets_workspace_id
        UNIQUE (workspace_id, id)
);

-- 5. DATASET COLUMNS
CREATE TABLE dataset_columns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL,
    column_name VARCHAR(150) NOT NULL,
    data_type VARCHAR(50) NOT NULL,
    allowed_aggregations VARCHAR(500),

    CONSTRAINT fk_dataset_columns_dataset
        FOREIGN KEY (dataset_id) REFERENCES datasets(id),

    CONSTRAINT uq_dataset_column
        UNIQUE (dataset_id, column_name)
);

-- 6. DASHBOARDS
CREATE TABLE dashboards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_dashboards_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces(id),

    CONSTRAINT fk_dashboards_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id),

    CONSTRAINT uq_dashboards_workspace_id
        UNIQUE (workspace_id, id)
);

-- 7. WIDGET CONFIGS
CREATE TABLE widget_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dashboard_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    widget_name VARCHAR(150) NOT NULL,
    chart_type VARCHAR(50) NOT NULL,
    metric_column_key VARCHAR(150),
    aggregation VARCHAR(50),
    group_by_column_key VARCHAR(150),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_widget_configs_dashboard
        FOREIGN KEY (workspace_id, dashboard_id)
        REFERENCES dashboards(workspace_id, id),

    CONSTRAINT fk_widget_configs_dataset
        FOREIGN KEY (workspace_id, dataset_id)
        REFERENCES datasets(workspace_id, id),

    CONSTRAINT fk_widget_configs_workspace
        FOREIGN KEY (workspace_id) REFERENCES workspaces(id)
);

-- 8. SALES RECORDS (sample dataset table)
CREATE TABLE sales_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL,
    region VARCHAR(100),
    product VARCHAR(150),
    amount NUMERIC(15, 2),
    quantity INTEGER,
    sale_date DATE,

    CONSTRAINT fk_sales_records_dataset
        FOREIGN KEY (dataset_id) REFERENCES datasets(id)
);

-- Indexes for commonly used relationships and lookups
CREATE INDEX idx_workspaces_created_by
    ON workspaces(created_by_user_id);

CREATE INDEX idx_workspace_members_user
    ON workspace_members(user_id);

CREATE INDEX idx_datasets_workspace
    ON datasets(workspace_id);

CREATE INDEX idx_dataset_columns_dataset
    ON dataset_columns(dataset_id);

CREATE INDEX idx_dashboards_workspace
    ON dashboards(workspace_id);

CREATE INDEX idx_dashboards_created_by
    ON dashboards(created_by_user_id);

CREATE INDEX idx_widget_configs_dashboard
    ON widget_configs(dashboard_id);

CREATE INDEX idx_widget_configs_dataset
    ON widget_configs(dataset_id);

CREATE INDEX idx_sales_records_dataset
    ON sales_records(dataset_id);
